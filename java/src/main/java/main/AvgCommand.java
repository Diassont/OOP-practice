package main;

/**
 * Клас для виконання команди обчислення середнього значення висоти елементів.
 * Перевіряє, чи висота елемента не є нульовою, і якщо так — додає її до суми.
 * @author Ярослав Пічугін
 * @version 1.0
 */
public class AvgCommand implements Command {
    /** Об'єкт, що містить всі елементи для обчислення середнього значення. */
    private final ViewResult view;
    
    /** Сума всіх висот елементів для обчислення середнього значення. */
    private double sum = 0;
    
    /** Лічильник кількості елементів з ненульовою висотою. */
    private int count = 0;

    /**
     * Конструктор класу. Ініціалізує об'єкт {@linkplain ViewResult}.
     * @param view Об'єкт для доступу до елементів і їх параметрів.
     */
    public AvgCommand(ViewResult view) {
        this.view = view;
    }

    /**
     * Виконує обчислення середнього значення висоти елементів.
     * Перевіряє кожен елемент на наявність ненульової висоти.
     * Якщо висота ненульова, додає її до суми та збільшує лічильник.
     */
    @Override
    public void execute() {
        // Проходимо по всіх елементах
        for (Item2d item : view.getItems()) {
            // Перевірка, чи висота не дорівнює нулю
            if (item.getHeight() != 0) {
                sum += item.getHeight();  // Додаємо висоту до суми
                count++;  // Збільшуємо лічильник
            } else {
                // Якщо висота нульова, виводимо попередження
                System.out.println("Попередження: Елемент має нульову висоту. Пропускаємо...");
            }
        }

        // Якщо є елементи для обчислення середнього значення
        if (count > 0) {
            double avg = sum / count;  // Обчислюємо середнє значення
            System.out.println("Середнє значення: " + avg);  // Виводимо результат
        } else {
            // Якщо немає елементів з ненульовою висотою
            System.out.println("Попередження: Немає елементів для обчислення середнього значення.");
        }
    }

    /**
     * Повертає результат виконання команди — середнє значення висоти.
     * @return Середнє значення висоти елементів.
     */
    public double getResult() {
        // Повертаємо результат, якщо є елементи для обчислення
        return (count > 0) ? sum / count : 0;
    }
}
